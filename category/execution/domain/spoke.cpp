// Where that code holds each immutable, as a 32-byte word: the
// immutableReferences of the same build.
constexpr std::array<size_t, 4> DOMAIN_CHAIN_ID_OFFSETS{422, 1089, 1272, 2103};
constexpr std::array<size_t, 2> L1_CHAIN_ID_OFFSETS{359, 1445};
constexpr std::array<size_t, 2> HUB_OFFSETS{784, 1479};

void set_immutable(
    byte_string &code, std::span<size_t const> const offsets,
    bytes32_t const &word)
{
    for (size_t const offset : offsets) {
        MONAD_ASSERT(offset + sizeof(word.bytes) <= code.size());
        std::ranges::copy(
            word.bytes, code.begin() + static_cast<ptrdiff_t>(offset));
    }
}

