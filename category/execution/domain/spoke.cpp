byte_string domain_spoke_code(
    uint64_t const domain_chain_id, uint64_t const l1_chain_id,
    Address const &hub)
{
    byte_string code{SPOKE_CODE};
    set_immutable(
        code,
        DOMAIN_CHAIN_ID_OFFSETS,
        store_be_as<bytes32_t>(uint256_t{domain_chain_id}));
    set_immutable(
        code,
        L1_CHAIN_ID_OFFSETS,
        store_be_as<bytes32_t>(uint256_t{l1_chain_id}));
    bytes32_t hub_word{};
    std::ranges::copy(
        hub.bytes, hub_word.bytes + sizeof(hub_word.bytes) - sizeof(hub.bytes));
    set_immutable(code, HUB_OFFSETS, hub_word);
    return code;
}

