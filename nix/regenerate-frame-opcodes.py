"""Regenerate keeps_frame from linked ZisK handlers in a private build."""

import argparse
import hashlib
import os
from pathlib import Path
import re
import runpy
import shutil
import subprocess
import tempfile

audit = runpy.run_path(str(Path(__file__).with_name("check-zisk.py")))
POLICY = Path("category/vm/interpreter/frame_opcodes.inc")
TARGET = "riscv64ima-zisk-zkvm-elf"
MODES = ("production", "deferred-selftest", "eager-selftest")
SLOT = re.compile(r"monad_vm_slot_(?:0[89]|1[0-5])_([0-9a-f]{2})(?:_[1-6]|_body)?")
BANNER = "// Generated by nix/regenerate-frame-opcodes.py.\n"


def render(names, deferred, eager):
    def cases(opcodes):
        if not opcodes:
            return ""
        return "".join(f"case {names[op]}:\n" for op in sorted(opcodes)) + "    return true;\n"

    text = BANNER + cases(deferred & eager)
    for condition, opcodes in (("!", deferred - eager), ("", eager - deferred)):
        if opcodes:
            text += f"#if {condition}defined(MONAD_ZKVM_GAS_CHECK_EVERY_OPCODE)\n"
            text += cases(opcodes) + "#endif\n"
    return text


def inspect(elf, prefix):
    def tool(name, *args):
        return subprocess.check_output([prefix + name, *args, elf], text=True)

    symbols = tool("nm", "--print-size", "--defined-only")
    sizes = audit["parse_function_sizes"](symbols)
    copies = ("", "_1", "_2", "_3", "_4", "_5")
    if "monad_vm_slot_15_00_lead_dup" not in sizes:
        copies += ("_6",)
    # Reject an ELF with a missing revision/copy, even if its remaining jumps pass.
    for rev in range(8, 16):
        for op in range(256):
            for suffix in copies:
                name = f"monad_vm_slot_{rev:02}_{op:02x}{suffix}"
                if not sizes.get(name):
                    raise ValueError(f"missing handler {name} in {elf}")

    unsafe = set()

    def record(name, message):
        match = SLOT.fullmatch(name)
        if not match:
            # A PUSH pair or standalone helper has a separate dispatch policy.
            raise ValueError(f"keeps_frame cannot fix this jump: {message}")
        unsafe.add(int(match[1], 16))

    count = audit["check_hand_made_jumps"](
        tool("objdump", "-d"), audit["manual_jump_addresses"](symbols), sizes,
        on_violation=record)
    return count, unsafe


def build(repo, target_dir, mode, policy):
    eager = mode == "eager-selftest"
    flags = os.environ.get("MONAD_ZKVM_CMAKE_ARGS", "")
    for option, enabled in (("SELFTEST", False), ("GAS_SELFTEST", mode != "production"),
                            ("GAS_CHECK_EVERY_OPCODE", eager)):
        flags += f" -DMONAD_ZKVM_{option}={'ON' if enabled else 'OFF'}"
    identity = f"frames-{mode}-{hashlib.sha256(policy.encode()).hexdigest()[:16]}"
    env = dict(os.environ, MONAD_ZKVM_CMAKE_ARGS=flags, MONAD_ZKVM_BUILD_ID=identity)
    subprocess.run(["cargo", "build", "--release", "--locked", "--target", TARGET,
                    "--target-dir", target_dir, "--bin", "monad-zkvm-zisk"],
                   cwd=repo / "zkvm/zisk", env=env, check=True)
    elf = target_dir / TARGET / "release/monad-zkvm-zisk"
    if f";build={identity}\0".encode() not in elf.read_bytes():
        raise ValueError(f"stale ELF: expected build marker {identity}")
    return elf


def converge(names, measure):
    deferred, eager = set(), set()
    while True:
        policy = render(names, deferred, eager)
        found = {mode: measure(mode, policy) for mode in MODES}
        for mode, unsafe_opcodes in found.items():
            excluded = eager if mode == "eager-selftest" else deferred
            still_unsafe = unsafe_opcodes & excluded
            if still_unsafe:
                raise ValueError(f"{mode}: unsafe jump persists with compiler dispatch: "
                                 + ", ".join(names[op] for op in sorted(still_unsafe)))
        if not any(found.values()):
            return policy
        deferred.update(found["production"], found["deferred-selftest"])
        eager.update(found["eager-selftest"])


def regenerate(repo, work, prefix):
    # Copy the guest and interpreter so an interrupted probe cannot expose an
    # unsafe policy in the checkout. Share the read-only dependency sources.
    source = work / "source"
    source.mkdir()
    for directory in ("category", "zkvm", "cmake"):
        shutil.copytree(repo / directory, source / directory,
                        ignore=shutil.ignore_patterns("target", "__pycache__"))
    (source / "third_party").symlink_to(repo / "third_party", target_is_directory=True)
    if (repo / ".cargo").is_dir():
        shutil.copytree(repo / ".cargo", source / ".cargo")
    enums = (source / "category/vm/evm/opcodes.hpp").read_text()
    names = {int(value, 16): name for name, value in re.findall(
        r"^\s*([A-Z][A-Z0-9_]*) = (0x[0-9a-fA-F]+),", enums, re.M)}

    def measure(mode, policy):
        path = source / POLICY
        if path.read_text() != policy:
            path.write_text(policy)
        elf = build(source, work / "target", mode, policy)
        count, unsafe = inspect(elf, prefix)
        print(f"{mode}: {count} jumps checked; unsafe opcodes: "
              + (", ".join(names[op] for op in sorted(unsafe)) or "none"), flush=True)
        return unsafe

    return converge(names, measure)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--binutils-prefix", required=True)
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args()
    for tool in ("nm", "objdump"):
        if not shutil.which(args.binutils_prefix + tool):
            parser.error(f"missing binutils executable: {args.binutils_prefix}{tool}")
    repo = args.repo.resolve()
    path = repo / POLICY
    original = path.read_bytes()
    with tempfile.TemporaryDirectory(prefix="zisk-frame-opcodes-") as work:
        result = regenerate(repo, Path(work), args.binutils_prefix).encode()
    if path.read_bytes() != original:
        parser.exit(1, "Policy changed during regeneration; rerun.\n")
    if result == original:
        print("Frame opcode policy is up to date.")
    elif args.check:
        parser.exit(1, "Frame opcode policy needs regeneration.\n")
    else:
        with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as tmp:
            tmp.write(result)
        os.chmod(tmp.name, path.stat().st_mode)
        os.replace(tmp.name, path)
        print(f"Updated {path}")


if __name__ == "__main__":
    main()
