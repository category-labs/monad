// and checked in. remappings-note.txt has the exact solc invocation; the
// build does not depend on solc, and the machine the corpus is generated on
// does not have it.
//
// Built for PARIS. solc targets Shanghai or later by default and emits PUSH0
// there, which Paris rejects -- the constructor then reverts, the block still
// executes, every root still agrees, and the contract is simply absent. The
// only thing that catches it is the deployment receipt's status.
//
// Creation and not runtime, because the contract has two immutables
// (NAMESPACE_CHAIN_ID, OPERATOR) that the constructor writes into the runtime
// code. Seeding a --bin-runtime would leave their slots unfilled, so the
// corpus deploys it with a CREATE transaction and lets the EVM substitute --
// which also means its address is keccak(rlp([sender, nonce])).
//
// The constructor takes (uint64 namespaceChainId, address operator), ABI
// encoded and appended to this.

