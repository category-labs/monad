"""Writes src/ecrecover_tables.rs: a*G + b*2^128*G on secp256k1 for
0 <= a, b < 64, (a, b) != (0, 0), at index a + 64*b - 1, affine, as the
little-endian 64-bit limbs ZisK's curve precompiles take. Run from zkvm/zisk:
python3 gen_ecrecover_tables.py > src/ecrecover_tables.rs"""

P = 2**256 - 2**32 - 977
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
G = (
    0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798,
    0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8,
)


def add_points(p, q):
    if p is None:
        return q
    if q is None:
        return p
    if p[0] == q[0]:
        if (p[1] + q[1]) % P == 0:
            return None
        slope = 3 * p[0] * p[0] * pow(2 * p[1], P - 2, P) % P
    else:
        slope = (q[1] - p[1]) * pow(q[0] - p[0], P - 2, P) % P
    x = (slope * slope - p[0] - q[0]) % P
    return (x, (slope * (p[0] - x) - p[1]) % P)


def multiply_point(scalar, point):
    accumulator = None
    for bit in bin(scalar)[2:]:
        accumulator = (
            add_points(accumulator, accumulator) if accumulator is not None else None
        )
        if bit == "1":
            accumulator = add_points(accumulator, point)
    return accumulator


def format_limbs(v):
    return ", ".join(f"0x{(v >> (64 * i)) & (2**64 - 1):016x}" for i in range(4))


assert multiply_point(N, G) is None
generator_high = multiply_point(2**128, G)
low_multiples, high_multiples = [None], [None]
for _ in range(63):
    low_multiples.append(add_points(low_multiples[-1], G))
    high_multiples.append(add_points(high_multiples[-1], generator_high))
rows = []
for table_index in range(1, 4096):
    x, y = add_points(
        low_multiples[table_index % 64], high_multiples[table_index // 64]
    )
    assert (y * y - x * x * x - 7) % P == 0
    rows.append(f"    SyscallPoint256 {{ x: [{format_limbs(x)}], y: [{format_limbs(y)}] }},")
